class ActivateView(discord.ui.View):

    def __init__(
        self,
        user_id: int,
        tickets: list,
    ):
        super().__init__(timeout=60)

        for ticket_id, booster_id, source in tickets:
            booster = BOOSTERS.get(booster_id)

            if booster is None:
                continue

            button = discord.ui.Button(
                label=booster["name"],
                style=discord.ButtonStyle.secondary,
                emoji=booster["emote"],
            )

            async def callback(
                interaction: discord.Interaction,
                ticket_id=ticket_id,
                booster_id=booster_id,
                source=source,
            ):
                if interaction.user.id != user_id:
                    await interaction.response.send_message(
                        "These Booster Tickets belong to another player.",
                        ephemeral=True,
                    )
                    return

                source_count = get_daily_source_activation_count(
                    user_id,
                    source,
                )

                if source_count >= 1:
                    if source == "daily":
                        message = (
                            "✦ You have already activated "
                            "your daily Booster today."
                        )
                    else:
                        message = (
                            "✦ You have already activated "
                            "a bought Booster today."
                        )

                    embed = discord.Embed(
                        description=message,
                        color=EMBED_COLOR,
                    )

                    await interaction.response.edit_message(
                        embed=embed,
                        view=None,
                    )
                    return

                total_count = (
                    get_daily_source_activation_count(
                        user_id,
                        "daily",
                    )
                    + get_daily_source_activation_count(
                        user_id,
                        "shop",
                    )
                )

                if total_count >= MAX_DAILY_ACTIVATIONS:
                    embed = discord.Embed(
                        description=(
                            "✦ **Daily Booster Limit Reached**\n\n"
                            "You can activate a maximum of "
                            "**2 boosters per day**.\n\n"
                            "✦ One daily Booster\n"
                            "✦ One bought Booster"
                        ),
                        color=EMBED_COLOR,
                    )

                    await interaction.response.edit_message(
                        embed=embed,
                        view=None,
                    )
                    return

                expires_at = activate_ticket(
                    ticket_id,
                    user_id,
                    booster_id,
                    source,
                )

                if expires_at is None:
                    embed = discord.Embed(
                        description=(
                            "✦ This Booster Ticket is no longer "
                            "available for activation."
                        ),
                        color=EMBED_COLOR,
                    )

                    await interaction.response.edit_message(
                        embed=embed,
                        view=None,
                    )
                    return

                booster = BOOSTERS[booster_id]

                embed = discord.Embed(
                    description=(
                        f"{booster['emote']} "
                        f"**{booster['name']} ACTIVATED**\n\n"
                        f"{booster['description']}\n\n"
                        "✦ Active for **24 hours**.\n"
                        "✦ Bought boosters can stack.\n\n"
                        f"✦ Activations today: "
                        f"**{total_count + 1}/2**"
                    ),
                    color=EMBED_COLOR,
                )

                await interaction.response.edit_message(
                    embed=embed,
                    view=None,
                )

            button.callback = callback
            self.add_item(button)


class Booster(commands.GroupCog, name="booster"):

    def __init__(self, bot: commands.Bot):
        self.bot = bot
        initialize_booster_database()

    @app_commands.command(
        name="shop",
        description="Browse and purchase Booster Tickets.",
    )
    async def shop(
        self,
        interaction: discord.Interaction,
    ):
        description = (
            "✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n\n"
            "**Booster Tickets**\n\n"
            "-# ✧ Each booster is valid for 24 hours "
            "once activated.\n"
            "-# ✧ You can activate **2 boosters per day**.\n"
            "-# ✧ One daily Booster + one bought Booster.\n"
            "-# ✧ Bought boosters can be stacked.\n"
            "-# ✧ Buying a ticket does not activate it.\n\n"
        )

        for booster in BOOSTERS.values():
            description += (
                f"{booster['emote']} **{booster['name']}**\n"
                f"-# {booster['description']}\n"
                f"{GLIMMER_EMOTE} **{booster['price']:,}**\n\n"
            )

        embed = discord.Embed(
            description=description,
            color=EMBED_COLOR,
        )

        header = discord.Embed(color=EMBED_COLOR)
        header.set_image(url=HEADER_URL)

        await interaction.response.send_message(
            embeds=[header, embed],
            view=ShopView(interaction.user.id),
        )


class Activate(commands.GroupCog, name="activate"):

    def __init__(self, bot: commands.Bot):
        self.bot = bot
        initialize_booster_database()

    @app_commands.command(
        name="boost",
        description="Activate one of your Booster Tickets.",
    )
    async def boost(
        self,
        interaction: discord.Interaction,
    ):
        user_id = interaction.user.id

        daily_count = get_daily_source_activation_count(
            user_id,
            "daily",
        )

        shop_count = get_daily_source_activation_count(
            user_id,
            "shop",
        )

        total_count = daily_count + shop_count

        if total_count >= MAX_DAILY_ACTIVATIONS:
            embed = discord.Embed(
                description=(
                    "✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n\n"
                    "**Daily Booster Limit Reached**\n\n"
                    "You have already activated "
                    "**2 boosters today**.\n\n"
                    "✦ One daily Booster\n"
                    "✦ One bought Booster\n\n"
                    "✦ ───── ⋆⋅☆⋅⋆ ───── ✦"
                ),
                color=EMBED_COLOR,
            )

            await interaction.response.send_message(
                embed=embed,
                ephemeral=True,
            )
            return

        tickets = get_available_tickets(user_id)

        if not tickets:
            embed = discord.Embed(
                description=(
                    "✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n\n"
                    f"{GLIMMER_EMOTE} **No Booster Tickets**\n\n"
                    "You don't have a Booster Ticket waiting.\n\n"
                    "✧ Use `/daily` to receive one.\n"
                    "✧ Or visit `/booster shop` to buy one.\n\n"
                    "✦ ───── ⋆⋅☆⋅⋆ ───── ✦"
                ),
                color=EMBED_COLOR,
            )

            await interaction.response.send_message(
                embed=embed,
                ephemeral=True,
            )
            return

        available_buttons = []

        for ticket_id, booster_id, source in tickets:
            source_count = get_daily_source_activation_count(
                user_id,
                source,
            )

            if source_count >= 1:
                continue

            if booster_id not in BOOSTERS:
                continue

            available_buttons.append(
                (
                    ticket_id,
                    booster_id,
                    source,
                )
            )

        if not available_buttons:
            embed = discord.Embed(
                description=(
                    "✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n\n"
                    "**No Booster Available**\n\n"
                    "You have already used the available "
                    "daily/shop Booster activation for today.\n\n"
                    "✦ ───── ⋆⋅☆⋅⋆ ───── ✦"
                ),
                color=EMBED_COLOR,
            )

            await interaction.response.send_message(
                embed=embed,
                ephemeral=True,
            )
            return

        embed = discord.Embed(
            description=(
                "✦ ───── ⋆⋅☆⋅⋆ ───── ✦\n\n"
                "**Choose a Booster**\n\n"
                "Select the Booster Ticket you want to activate.\n\n"
                "✦ Active for **24 hours**.\n"
                "✦ Bought boosters can be stacked.\n\n"
                f"✦ Activations today: "
                f"**{total_count}/2**\n\n"
                "✦ ───── ⋆⋅☆⋅⋆ ───── ✦"
            ),
            color=EMBED_COLOR,
        )

        await interaction.response.send_message(
            embed=embed,
            view=ActivateView(
                user_id,
                available_buttons,
            ),
            ephemeral=True,
        )


async def setup(bot: commands.Bot):
    await bot.add_cog(Booster(bot))
    await bot.add_cog(Activate(bot))
