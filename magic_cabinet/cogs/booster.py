def initialize_booster_database():
    """Create the booster tables in Neon PostgreSQL."""
    with get_connection() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS booster_tickets (
                ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                user_id BIGINT NOT NULL,
                booster_id TEXT NOT NULL,
                received_at TEXT NOT NULL,
                source TEXT NOT NULL DEFAULT 'daily',
                activated_at TEXT,
                expires_at TEXT,
                uses_remaining INTEGER
            )
            """
        )

        connection.execute(
            """
            ALTER TABLE booster_tickets
            ADD COLUMN IF NOT EXISTS source TEXT
            NOT NULL DEFAULT 'daily'
            """
        )

        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS booster_activation_log (
                activation_id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                user_id BIGINT NOT NULL,
                ticket_id BIGINT NOT NULL,
                booster_id TEXT NOT NULL,
                source TEXT NOT NULL DEFAULT 'daily',
                activated_at TEXT NOT NULL
            )
            """
        )

        connection.execute(
            """
            ALTER TABLE booster_activation_log
            ADD COLUMN IF NOT EXISTS source TEXT
            NOT NULL DEFAULT 'daily'
            """
        )

        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS
                idx_booster_tickets_user
            ON booster_tickets (user_id, activated_at)
            """
        )

        connection.execute(
            """
            CREATE INDEX IF NOT EXISTS
                idx_booster_activation_user
            ON booster_activation_log (user_id, source, activated_at)
            """
        )


def get_glimmers(user_id: int) -> int:
    with get_connection() as connection:
        row = connection.execute(
            """
            SELECT glimmers
            FROM balances
            WHERE user_id = %s
            """,
            (user_id,),
        ).fetchone()

    return 0 if row is None else row["glimmers"]


def purchase_booster(
    user_id: int,
    booster_id: str,
    price: int,
) -> bool:
    now = datetime.now(timezone.utc)

    with get_connection() as connection:
        cursor = connection.execute(
            """
            UPDATE balances
            SET glimmers = glimmers - %s
            WHERE user_id = %s
            AND glimmers >= %s
            """,
            (price, user_id, price),
        )

        if cursor.rowcount != 1:
            return False

        connection.execute(
            """
            INSERT INTO booster_tickets (
                user_id,
                booster_id,
                received_at,
                source
            )
            VALUES (%s, %s, %s, 'shop')
            """,
            (
                user_id,
                booster_id,
                now.isoformat(),
            ),
        )

    return True


def get_available_tickets(user_id: int):
    with get_connection() as connection:
        rows = connection.execute(
            """
            SELECT ticket_id, booster_id, source
            FROM booster_tickets
            WHERE user_id = %s
            AND activated_at IS NULL
            ORDER BY ticket_id ASC
            """,
            (user_id,),
        ).fetchall()

    return [
        (
            row["ticket_id"],
            row["booster_id"],
            row["source"],
        )
        for row in rows
    ]


def get_active_boosters(user_id: int):
    now = datetime.now(timezone.utc).isoformat()

    with get_connection() as connection:
        rows = connection.execute(
            """
            SELECT
                ticket_id,
                booster_id,
                source,
                expires_at,
                uses_remaining
            FROM booster_tickets
            WHERE user_id = %s
            AND activated_at IS NOT NULL
            AND expires_at > %s
            ORDER BY activated_at ASC
            """,
            (user_id, now),
        ).fetchall()

    return [
        (
            row["ticket_id"],
            row["booster_id"],
            row["source"],
            row["expires_at"],
            row["uses_remaining"],
        )
        for row in rows
    ]


def get_daily_source_activation_count(
    user_id: int,
    source: str,
) -> int:
    today = datetime.now(timezone.utc).date().isoformat()

    with get_connection() as connection:
        row = connection.execute(
            """
            SELECT COUNT(*) AS activation_count
            FROM booster_activation_log
            WHERE user_id = %s
            AND source = %s
            AND LEFT(activated_at, 10) = %s
            """,
            (
                user_id,
                source,
                today,
            ),
        ).fetchone()

    return 0 if row is None else row["activation_count"]


def activate_ticket(
    ticket_id: int,
    user_id: int,
    booster_id: str,
    source: str,
):
    now = datetime.now(timezone.utc)
    expires_at = now + BOOSTER_DURATION
    uses = BOOSTERS[booster_id]["uses"]

    with get_connection() as connection:
        cursor = connection.execute(
            """
            UPDATE booster_tickets
            SET activated_at = %s,
                expires_at = %s,
                uses_remaining = %s
            WHERE ticket_id = %s
            AND user_id = %s
            AND booster_id = %s
            AND source = %s
            AND activated_at IS NULL
            """,
            (
                now.isoformat(),
                expires_at.isoformat(),
                uses,
                ticket_id,
                user_id,
                booster_id,
                source,
            ),
        )

        if cursor.rowcount != 1:
            return None

        connection.execute(
            """
            INSERT INTO booster_activation_log (
                user_id,
                ticket_id,
                booster_id,
                source,
                activated_at
            )
            VALUES (%s, %s, %s, %s, %s)
            """,
            (
                user_id,
                ticket_id,
                booster_id,
                source,
                now.isoformat(),
            ),
        )

    return expires_at


class ConfirmPurchaseView(discord.ui.View):

    def __init__(
        self,
        user_id: int,
        booster_id: str,
    ):
        super().__init__(timeout=60)
        self.user_id = user_id
        self.booster_id = booster_id

    @discord.ui.button(
        label="Confirm Purchase",
        style=discord.ButtonStyle.success,
    )
    async def confirm(
        self,
        interaction: discord.Interaction,
        button: discord.ui.Button,
    ):
        if interaction.user.id != self.user_id:
            await interaction.response.send_message(
                "This purchase confirmation belongs to another player.",
                ephemeral=True,
            )
            return

        booster = BOOSTERS[self.booster_id]

        if get_glimmers(self.user_id) < booster["price"]:
            embed = discord.Embed(
                description=(
                    f"{booster['emote']} **Not enough Glimmers**\n\n"
                    f"You need **{booster['price']:,}** "
                    f"{GLIMMER_EMOTE}."
                ),
                color=EMBED_COLOR,
            )

            await interaction.response.edit_message(
                embed=embed,
                view=None,
            )
            return

        success = purchase_booster(
            self.user_id,
            self.booster_id,
            booster["price"],
        )

        if not success:
            embed = discord.Embed(
                description=(
                    "✦ Your purchase could not be completed. "
                    "Please try again."
                ),
                color=EMBED_COLOR,
            )

            await interaction.response.edit_message(
                embed=embed,
                view=None,
            )
            return

        embed = discord.Embed(
            description=(
                f"{booster['emote']} **{booster['name']}**\n\n"
                f"Your {booster['emote']} **{booster['name']}** "
                "has been successfully bought.\n\n"
                "✦ This booster is valid for **24 hours** "
                "once activated.\n\n"
                "✦ Bought boosters can be stacked.\n\n"
                "To activate the booster, use `/activate boost`."
            ),
            color=EMBED_COLOR,
        )

        await interaction.response.edit_message(
            embed=embed,
            view=None,
        )


