import json
from datetime import datetime, timezone

from magic_cabinet.postgres_database import (
    get_postgres_connection,
    initialize_postgres_database,
)


def initialize_tracker_database():
    """Ensure PostgreSQL has the weekly tracker tables."""
    initialize_postgres_database()

    with get_postgres_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS weekly_notifications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                task_id TEXT NOT NULL,
                created_at TEXT NOT NULL,
                sent INTEGER NOT NULL DEFAULT 0
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS weekly_delivery (
                user_id BIGINT PRIMARY KEY,
                guild_id BIGINT NOT NULL,
                channel_id BIGINT NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS weekly_pending_rewards (
                reward_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                reward_type TEXT NOT NULL,
                amount INTEGER NOT NULL DEFAULT 0,
                task_id TEXT,
                claimed INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL
            )
        """)


def save_weekly_channel(user_id, guild_id, channel_id):
    """Save the channel used for weekly challenge notifications."""
    initialize_tracker_database()

    with get_postgres_connection() as conn:
        conn.execute(
            """
            INSERT INTO weekly_delivery (user_id, guild_id, channel_id)
            VALUES (%s, %s, %s)
            ON CONFLICT (user_id)
            DO UPDATE SET
                guild_id = EXCLUDED.guild_id,
                channel_id = EXCLUDED.channel_id
            """,
            (user_id, guild_id, channel_id),
        )


def record_weekly_progress(user_id, task_id, amount=1):
    """Update weekly challenge progress and create rewards/notifications."""
    initialize_tracker_database()

    now = datetime.now(timezone.utc).isoformat()

    with get_postgres_connection() as conn:
        challenge = conn.execute(
            """
            SELECT task_data
            FROM weekly_challenges
            WHERE user_id = %s
            """,
            (user_id,),
        ).fetchone()

        if not challenge:
            return

        task_data = challenge["task_data"]

        if isinstance(task_data, str):
            try:
                task_data = json.loads(task_data)
            except (json.JSONDecodeError, TypeError):
                return

        if not isinstance(task_data, dict) or task_id not in task_data:
            return

        task = task_data[task_id]

        if not isinstance(task, dict):
            return

        target = int(task.get("target", 1))

        progress_row = conn.execute(
            """
            SELECT progress, completed
            FROM weekly_progress
            WHERE user_id = %s AND task_id = %s
            """,
            (user_id, task_id),
        ).fetchone()

        if progress_row and progress_row["completed"]:
            return

        old_progress = progress_row["progress"] if progress_row else 0
        new_progress = min(old_progress + amount, target)
        completed = int(new_progress >= target)

        conn.execute(
            """
            INSERT INTO weekly_progress
                (user_id, task_id, progress, completed)
            VALUES (%s, %s, %s, %s)
            ON CONFLICT (user_id, task_id)
            DO UPDATE SET
                progress = EXCLUDED.progress,
                completed = EXCLUDED.completed
            """,
            (user_id, task_id, new_progress, completed),
        )

        if completed and not (progress_row and progress_row["completed"]):
            conn.execute(
                """
                INSERT INTO weekly_notifications
                    (user_id, task_id, created_at, sent)
                VALUES (%s, %s, %s, 0)
                """,
                (user_id, task_id, now),
            )

            reward_amount = int(task.get("reward", 0))

            if reward_amount > 0:
                conn.execute(
                    """
                    INSERT INTO weekly_pending_rewards
                        (user_id, reward_type, amount, task_id,
                         claimed, created_at)
                    VALUES (%s, 'task_glimmers', %s, %s, 0, %s)
                    """,
                    (user_id, reward_amount, task_id, now),
                )

        completed_count = conn.execute(
            """
            SELECT COUNT(*) AS total
            FROM weekly_progress
            WHERE user_id = %s AND completed = 1
            """,
            (user_id,),
        ).fetchone()["total"]

        if completed_count >= 3:
            grand_reward_exists = conn.execute(
                """
                SELECT reward_id
                FROM weekly_pending_rewards
                WHERE user_id = %s
                  AND reward_type = 'grand_reward'
                  AND claimed = 0
                LIMIT 1
                """,
                (user_id,),
            ).fetchone()

            if not grand_reward_exists:
                already_claimed = conn.execute(
                    """
                    SELECT reward_claimed
                    FROM weekly_challenges
                    WHERE user_id = %s
                    """,
                    (user_id,),
                ).fetchone()

                if already_claimed and not already_claimed["reward_claimed"]:
                    conn.execute(
                        """
                        INSERT INTO weekly_pending_rewards
                            (user_id, reward_type, amount, task_id,
                             claimed, created_at)
                        VALUES (%s, 'grand_reward', 25000, NULL, 0, %s)
                        """,
                        (user_id, now),
                    )

                    conn.execute(
                        """
                        UPDATE weekly_challenges
                        SET reward_claimed = 1
                        WHERE user_id = %s
                        """,
                        (user_id,),
                    )


def get_pending_notifications():
    """Return unsent weekly notifications with their destination channels."""
    initialize_tracker_database()

    with get_postgres_connection() as conn:
        rows = conn.execute(
            """
            SELECT
                n.id,
                n.user_id,
                n.task_id,
                n.created_at,
                d.guild_id,
                d.channel_id
            FROM weekly_notifications AS n
            JOIN weekly_delivery AS d
                ON d.user_id = n.user_id
            WHERE n.sent = 0
            ORDER BY n.id
            """
        ).fetchall()

    return rows


def mark_notification_sent(notification_id):
    """Mark a weekly notification as sent."""
    initialize_tracker_database()

    with get_postgres_connection() as conn:
        conn.execute(
            """
            UPDATE weekly_notifications
            SET sent = 1
            WHERE id = %s
            """,
            (notification_id,),
        )


def get_pending_rewards(user_id):
    """Return unclaimed weekly rewards for a player."""
    initialize_tracker_database()

    with get_postgres_connection() as conn:
        return conn.execute(
            """
            SELECT reward_id, reward_type, amount, task_id
            FROM weekly_pending_rewards
            WHERE user_id = %s AND claimed = 0
            ORDER BY reward_id
            """,
            (user_id,),
        ).fetchall()
