
"""PostgreSQL database helpers for Magic Cabinet."""

import os
import psycopg


def get_postgres_connection():
    database_url = os.getenv("DATABASE_URL")
    if not database_url:
        raise RuntimeError("DATABASE_URL is not configured.")

    return psycopg.connect(database_url, connect_timeout=10)


def initialize_postgres_database():
    """Create all known Magic Cabinet tables safely."""

    statements = [
        """
        CREATE TABLE IF NOT EXISTS drop_channels (
            guild_id BIGINT PRIMARY KEY,
            channel1_id BIGINT NOT NULL,
            channel2_id BIGINT,
            channel3_id BIGINT,
            channel4_id BIGINT,
            channel5_id BIGINT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS players (
            user_id BIGINT PRIMARY KEY,
            created_at TEXT NOT NULL,
            vault TEXT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS player_vaults (
            user_id BIGINT NOT NULL,
            vault TEXT NOT NULL,
            PRIMARY KEY (user_id, vault)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS balances (
            user_id BIGINT PRIMARY KEY,
            glimmers BIGINT NOT NULL DEFAULT 0
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS bag (
            user_id BIGINT NOT NULL,
            card_id BIGINT NOT NULL,
            quantity INTEGER NOT NULL DEFAULT 0,
            PRIMARY KEY (user_id, card_id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS daily_data (
            user_id BIGINT PRIMARY KEY,
            last_claim_at TEXT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS booster_tickets (
            ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL,
            booster_id TEXT NOT NULL,
            received_at TEXT NOT NULL,
            activated_at TEXT,
            expires_at TEXT,
            uses_remaining INTEGER,
            source TEXT NOT NULL DEFAULT 'daily'
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS player_badges (
            user_id BIGINT NOT NULL,
            badge_id TEXT NOT NULL,
            badge_name TEXT NOT NULL,
            badge_emote TEXT,
            PRIMARY KEY (user_id, badge_id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS player_achievements (
            user_id BIGINT NOT NULL,
            achievement_id TEXT NOT NULL,
            achievement_name TEXT NOT NULL,
            global_rank INTEGER NOT NULL,
            PRIMARY KEY (user_id, achievement_id)
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS player_card_inventory (
            user_id BIGINT NOT NULL,
            card_id BIGINT NOT NULL,
            quantity INTEGER NOT NULL DEFAULT 1
                CHECK (quantity >= 1),
            PRIMARY KEY (user_id, card_id)
        )
        """,
    ]

    with get_postgres_connection() as connection:
        with connection.cursor() as cursor:
            for statement in statements:
                cursor.execute(statement)

    print("[POSTGRES] All currently known tables initialized.")
