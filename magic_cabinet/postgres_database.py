
"""PostgreSQL database helpers for Magic Cabinet."""

import os
import psycopg


TABLES = {
    "drop_channels": """
        CREATE TABLE IF NOT EXISTS drop_channels (
            guild_id BIGINT PRIMARY KEY,
            channel1_id BIGINT NOT NULL,
            channel2_id BIGINT,
            channel3_id BIGINT,
            channel4_id BIGINT,
            channel5_id BIGINT
        )
    """,
    "players": """
        CREATE TABLE IF NOT EXISTS players (
            user_id BIGINT PRIMARY KEY,
            created_at TEXT NOT NULL,
            vault TEXT
        )
    """,
    "player_vaults": """
        CREATE TABLE IF NOT EXISTS player_vaults (
            user_id BIGINT NOT NULL,
            vault TEXT NOT NULL,
            PRIMARY KEY (user_id, vault)
        )
    """,
    "balances": """
        CREATE TABLE IF NOT EXISTS balances (
            user_id BIGINT PRIMARY KEY,
            glimmers BIGINT NOT NULL DEFAULT 0
        )
    """,
    "bag": """
        CREATE TABLE IF NOT EXISTS bag (
            user_id BIGINT NOT NULL,
            card_id BIGINT NOT NULL,
            quantity INTEGER NOT NULL DEFAULT 0,
            PRIMARY KEY (user_id, card_id)
        )
    """,
    "daily_data": """
        CREATE TABLE IF NOT EXISTS daily_data (
            user_id BIGINT PRIMARY KEY,
            last_claim_at TEXT
        )
    """,
    "booster_tickets": """
        CREATE TABLE IF NOT EXISTS booster_tickets (
            ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL,
            booster_id TEXT NOT NULL,
            received_at TEXT NOT NULL,
            activated_at TEXT,
            expires_at TEXT,
            uses_remaining INTEGER,
            source TEXT NOT NULL DEFAULT 'daily'
        )
    """,
    "player_badges": """
        CREATE TABLE IF NOT EXISTS player_badges (
            user_id BIGINT NOT NULL,
            badge_id TEXT NOT NULL,
            badge_name TEXT NOT NULL,
            badge_emote TEXT,
            PRIMARY KEY (user_id, badge_id)
        )
    """,
    "player_achievements": """
        CREATE TABLE IF NOT EXISTS player_achievements (
            user_id BIGINT NOT NULL,
            achievement_id TEXT NOT NULL,
            achievement_name TEXT NOT NULL,
            global_rank INTEGER NOT NULL,
            PRIMARY KEY (user_id, achievement_id)
        )
    """,
    "player_card_inventory": """
        CREATE TABLE IF NOT EXISTS player_card_inventory (
            user_id BIGINT NOT NULL,
            card_id BIGINT NOT NULL,
            quantity INTEGER NOT NULL DEFAULT 1
                CHECK (quantity >= 1),
            PRIMARY KEY (user_id, card_id)
        )
    """,
}


def get_postgres_connection():
    """Open a PostgreSQL connection."""

    database_url = os.getenv("DATABASE_URL")

    if not database_url:
        raise RuntimeError("DATABASE_URL is not configured.")

    return psycopg.connect(
        database_url,
        connect_timeout=10,
    )


def initialize_postgres_database():
    """Create known PostgreSQL tables without deleting data."""

    with get_postgres_connection() as connection:
        with connection.cursor() as cursor:
            for statement in TABLES.values():
                cursor.execute(statement)

    print("[POSTGRESQL] Known tables initialized.")


def check_postgres_tables():
    """Report table existence and row counts without modifying data."""

    with get_postgres_connection() as connection:
        with connection.cursor() as cursor:
            for table in TABLES:
                cursor.execute(
                    """
                    SELECT EXISTS (
                        SELECT 1
                        FROM information_schema.tables
                        WHERE table_schema = 'public'
                          AND table_name = %s
                    )
                    """,
                    (table,),
                )

                exists = cursor.fetchone()[0]

                if not exists:
                    print(f"[DB CHECK] {table}: missing")
                    continue

                cursor.execute(
                    f'SELECT COUNT(*) FROM public."{table}"'
                )
                count = cursor.fetchone()[0]

                print(f"[DB CHECK] {table}: {count} rows")


if __name__ == "__main__":
    check_postgres_tables()
